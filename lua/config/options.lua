-- Indentazione: 4 spazi
vim.opt.tabstop = 4      -- un carattere Tab viene mostrato largo 4 colonne
vim.opt.shiftwidth = 4   -- >>, << e l'indentazione automatica spostano di 4 colonne
vim.opt.softtabstop = 4  -- premendo Tab (o Backspace) ci si sposta di 4 colonne
vim.opt.expandtab = true -- il tasto Tab inserisce spazi invece di un carattere Tab
